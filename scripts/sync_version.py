"""Keep every copy of the version, and the generated docs, in step with VERSION.

  python scripts/sync_version.py               rewrite whatever drifted
  python scripts/sync_version.py --check       write nothing; exit 1 listing every drift
  python scripts/sync_version.py --only docs   only the generated docs (with --check: only check them)

VERSION (x.y.z) is the single source. From it:
  targeted edits   plugin/manifest.json "version"; the `VERSION = "..."` line of broker/broker.py and
                   broker/fake_panel.py; SKILL.md heading "(vX)"; README.md "(vX)" above the first "## "
                   heading; a `const VERSION = "..."` line in plugin/main.js or `CLI_VERSION = "..."` in
                   cli/ppro.py, if one is still there
  generated files  ppro_bridge/_version.py; plugin/lib/spec.js (scripts/panel_spec.render)
  generated docs   .claude/skills/ppro-bridge/SKILL.md and .agents/skills/ppro-bridge/SKILL.md (= SKILL.md),
                   AGENTS.md (= a fixed header + SKILL.md without its YAML frontmatter)
--check also requires a README.md changelog entry ("- **x.y.z**") for VERSION.

Edits are regex replacements of the version text only (no re-serialisation); files are written as UTF-8
with LF line endings, and only when their content changes.
"""

import argparse
import importlib.util
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
VERSION_RE = re.compile(r"\d+\.\d+\.\d+")

AGENTS_HEADER = (
    "# Agent instructions: Premiere Pro Agent Bridge\n"
    "\n"
    "This file follows the AGENTS.md convention (read by Codex and other coding agents).\n"
    "Claude Code users: the same content is packaged as a skill at `.claude/skills/ppro-bridge/SKILL.md`"
    " and is loaded automatically.\n"
)
SKILL = "SKILL.md"
SKILL_COPIES = (".claude/skills/ppro-bridge/SKILL.md", ".agents/skills/ppro-bridge/SKILL.md")
AGENTS = "AGENTS.md"
README = "README.md"
VERSION_PY = "ppro_bridge/_version.py"
SPEC_JSON = "ppro_bridge/actions.json"
SPEC_JS = "plugin/lib/spec.js"
VERSION_PY_TEXT = '# Generated by scripts/sync_version.py from VERSION. Do not edit.\nVERSION = "{v}"\n'


class SyncError(Exception):
    """A file the sync must edit is missing or does not have the expected shape."""


# (path, regex with groups (prefix)(version)(suffix), how many matches: "one" or "optional")
RULES = (
    ("plugin/manifest.json", r'^([ \t]*"version"[ \t]*:[ \t]*")([^"\n]*)(")', "one"),
    ("broker/broker.py", r'^(VERSION = ")([^"\n]*)(")(?=[ \t]*$)', "one"),
    ("broker/fake_panel.py", r'^(VERSION = ")([^"\n]*)(")(?=[ \t]*$)', "one"),
    ("plugin/main.js", r'^(const VERSION = ")([^"\n]*)(";)(?=[ \t]*$)', "optional"),
    ("cli/ppro.py", r'^(CLI_VERSION = ")([^"\n]*)(")(?=[ \t]*$)', "optional"),
    (SKILL, r"^(# Premiere Pro Agent Bridge \(v)([^)\n]*)(\))(?=[ \t]*$)", "one"),
)


def lf(text: str) -> str:
    return text.replace("\r\n", "\n").replace("\r", "\n")


def read_text(path: Path) -> str | None:
    """File text with any BOM and CR removed; None when the file does not exist."""
    if not path.is_file():
        return None
    return lf(path.read_bytes().decode("utf-8-sig"))


def split_frontmatter(text: str) -> tuple[str, str]:
    """("---\\n...\\n---\\n", body) of a skill file; the body keeps its leading blank line."""
    text = lf(text)
    if not text.startswith("---\n"):
        raise SyncError(f"{SKILL} must start with YAML frontmatter (a '---' line)")
    end = text.find("\n---\n", 3)
    if end < 0:
        raise SyncError(f"{SKILL}: the YAML frontmatter has no closing '---' line")
    return text[:end + 5], text[end + 5:]


def agents_md(skill_text: str) -> str:
    """AGENTS.md: the fixed header, one blank line, then SKILL.md without its frontmatter."""
    _, body = split_frontmatter(skill_text)
    return AGENTS_HEADER + "\n" + body.lstrip("\n")


def generated_docs(skill_text: str) -> dict[str, str]:
    skill_text = lf(skill_text)
    docs = {rel: skill_text for rel in SKILL_COPIES}
    docs[AGENTS] = agents_md(skill_text)
    return docs


def replace_version(text: str, pattern: str, how: str, version: str, rel: str) -> str:
    rx = re.compile(pattern, re.M)
    hits = rx.findall(text)
    if how == "one" and len(hits) != 1:
        raise SyncError(f"{rel}: expected one version line matching {pattern!r}, found {len(hits)}")
    if how == "optional" and len(hits) > 1:
        raise SyncError(f"{rel}: more than one version line matching {pattern!r}")
    return rx.sub(lambda m: m.group(1) + version + m.group(3), text)


def readme_heading(text: str, version: str) -> str:
    """Set "(vX.Y.Z)" in the part of README.md above its first "## " heading."""
    m = re.search(r"^## ", text, re.M)
    cut = m.start() if m else len(text)
    head, rest = text[:cut], text[cut:]
    rx = re.compile(r"(\(v)(\d+\.\d+\.\d+)(\))")
    if not rx.search(head):
        raise SyncError(f'{README}: no "(vX.Y.Z)" version mention above the first "## " heading')
    return rx.sub(lambda m: m.group(1) + version + m.group(3), head) + rest


def changelog_has(text: str, version: str) -> bool:
    m = re.search(r"^## Changelog\s*$(.*?)(?=^## |\Z)", text, re.M | re.S)
    return bool(m and re.search(r"^- \*\*" + re.escape(version) + r"\*\*", m.group(1), re.M))


def _panel_spec(root: Path):
    path = root / "scripts" / "panel_spec.py"
    if not path.is_file():  # a test tree without scripts/: use the renderer next to this file
        path = HERE / "panel_spec.py"
    spec = importlib.util.spec_from_file_location("_pab_panel_spec", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def read_version(root: Path) -> str:
    text = read_text(root / "VERSION")
    if text is None:
        raise SyncError("VERSION is missing")
    version = text.strip()
    if not VERSION_RE.fullmatch(version):
        raise SyncError(f"VERSION must be x.y.z (digits only), got {version!r}")
    return version


def plan(root: Path = REPO, *, only_docs: bool = False) -> dict[str, str]:
    """Every file the sync owns, mapped to the exact text it should have."""
    version = read_version(root)
    want: dict[str, str] = {}

    def current(rel: str) -> str:
        text = read_text(root / rel)
        if text is None:
            raise SyncError(f"{rel} is missing")
        return text

    skill = current(SKILL)
    if not only_docs:
        for rel, pattern, how in RULES:
            text = skill if rel == SKILL else read_text(root / rel)
            if text is None:
                if how == "optional":
                    continue
                raise SyncError(f"{rel} is missing")
            want[rel] = replace_version(text, pattern, how, version, rel)
        skill = want[SKILL]
        want[README] = readme_heading(current(README), version)
        want[VERSION_PY] = VERSION_PY_TEXT.format(v=version)
        spec = json.loads((root / SPEC_JSON).read_bytes().decode("utf-8-sig"))
        want[SPEC_JS] = lf(_panel_spec(root).render(spec, version))
    split_frontmatter(skill)  # refuse a SKILL.md without frontmatter before writing anything
    want.update(generated_docs(skill))
    return want


def drift(root: Path, want: dict[str, str]) -> list[str]:
    """Files whose bytes on disk differ from what they should be."""
    out = []
    for rel, text in want.items():
        path = root / rel
        if not path.is_file():
            out.append(f"{rel}: missing")
        elif path.read_bytes() != text.encode("utf-8"):
            out.append(f"{rel}: out of date")
    return out


def sync(root: Path = REPO, *, check: bool = False, only_docs: bool = False) -> tuple[list[str], list[str]]:
    """(problems, written). With check=True nothing is written and every drift is a problem."""
    want = plan(root, only_docs=only_docs)
    stale = drift(root, want)
    problems, written = [], []
    if check:
        problems += stale
        if not only_docs:
            version = read_version(root)
            if not changelog_has(read_text(root / README) or "", version):
                problems.append(f'{README}: no changelog entry "- **{version}**" under "## Changelog"')
        return problems, written
    for line in stale:
        rel = line.split(":", 1)[0]
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(want[rel].encode("utf-8"))
        written.append(rel)
    return problems, written


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(prog="sync_version", description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 listing every drift")
    parser.add_argument("--only", choices=["docs"], help="only the generated docs")
    args = parser.parse_args(argv)
    try:
        problems, written = sync(REPO, check=args.check, only_docs=args.only == "docs")
    except (SyncError, OSError, ValueError) as e:
        print(f"sync_version: {e}")
        return 1
    if args.check:
        for p in problems:
            print(f"DRIFT  {p}")
        if problems:
            hint = " (the changelog entry is written by hand)" if any("changelog" in p for p in problems) else ""
            print(f"{len(problems)} problem(s): run python scripts/sync_version.py"
                  + (" --only docs" if args.only else "") + hint)
            return 1
        print("in sync: " + read_version(REPO))
        return 0
    for rel in written:
        print(f"wrote  {rel}")
    print(f"{len(written)} file(s) written (VERSION {read_version(REPO)})" if written else "already in sync")
    return 0


if __name__ == "__main__":
    sys.exit(main())
