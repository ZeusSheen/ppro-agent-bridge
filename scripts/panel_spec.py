"""Render plugin/lib/spec.js — the panel's copy of the action spec — from ppro_bridge/actions.json.

Imported by scripts/sync_version.py; also runnable on its own:  python scripts/panel_spec.py [--check]
The panel uses it to refuse unknown actions and bad params before any handler runs, to know which actions may
run while it is stuck or on a denied build, and which capability an action needs.
"""

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SPEC = REPO / "ppro_bridge" / "actions.json"
OUT = REPO / "plugin" / "lib" / "spec.js"
HEADER = "// Generated by scripts/sync_version.py from VERSION and ppro_bridge/actions.json. Do not edit.\n"


def _strip(schema):
    """Drop documentation from a param schema, keep everything the validator reads."""
    if isinstance(schema, dict):
        return {k: _strip(v) for k, v in schema.items() if k != "doc"}
    if isinstance(schema, list):
        return [_strip(v) for v in schema]
    return schema


def panel_spec(spec: dict, version: str) -> dict:
    return {
        "version": version,
        "protocol": spec["protocol"],
        "defaultTimeoutSeconds": spec["defaultTimeoutSeconds"],
        "actions": {a["name"]: {"kind": a["kind"], "capability": a["capability"],
                                "allowedWhenStuck": a["allowedWhenStuck"], "allowedWhenDenied": a["allowedWhenDenied"],
                                "timeoutSeconds": a["timeoutSeconds"], "requireOneOf": a.get("requireOneOf", []),
                                "params": _strip(a["params"])}
                    for a in spec["actions"]},
    }


def render(spec: dict, version: str) -> str:
    return HEADER + "module.exports = " + json.dumps(panel_spec(spec, version), indent=1, ensure_ascii=True) + ";\n"


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    version = (REPO / "VERSION").read_text(encoding="utf-8").strip()
    text = render(json.loads(SPEC.read_text(encoding="utf-8")), version)
    if "--check" in argv:
        current = OUT.read_bytes().decode("utf-8") if OUT.exists() else None
        if current != text:
            print(f"{OUT.relative_to(REPO)} is out of date: run python scripts/sync_version.py")
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes(text.encode("utf-8"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
