"""Build the bridge's icon: ppro_bridge/bridge.svg (the 256-unit master), ppro_bridge/bridge.ico (16-256 px, the
shortcuts' icon) and plugin/icon.png (64 px, the panel's header, shown at 32 CSS px), all from the geometry below.

The design: an L-cut on a deep purple tile. Clip A's picture cuts first (x 64-80), its sound runs on and cuts later
(x 176-192), so one 16-unit Z-shaped seam steps between the two lavender clips. An orange playhead stands where the
picture is already clip B and the sound still clip A. The rim is the website's glass edge, one pixel at every size.

Every .ico frame is its own SVG with each coordinate snapped to that size's pixel grid (the playhead stem is one
whole pixel at 16 px, its head an odd width around it), drawn by a browser at exactly that size: the small frames are
sharp, not a 256 px render scaled down. Needs Playwright with the installed Edge or Chrome, and Pillow.

    python scripts/make_icon.py [--preview out.png]
"""

import argparse
import base64
import io
import math
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SVG = REPO / "ppro_bridge" / "bridge.svg"
ICO = REPO / "ppro_bridge" / "bridge.ico"
PANEL_PNG, PANEL_SIZE = REPO / "plugin" / "icon.png", 64
SIZES = (16, 20, 24, 32, 40, 48, 64, 128, 256)
TILE, CLIP_A, CLIP_B, PLAYHEAD = "#14143F", "#9999FF", "#C2C2FF", "#FF7A1A"
UNITS = 256


def icon_svg(n: int, comment: str = "") -> str:
    """The icon at n x n pixels, coordinates in pixels and snapped to whole pixels."""
    px = lambda u: int(math.floor(u * n / UNITS + 0.5))
    a = [(0, 96), (64, 96), (64, 160), (176, 160), (176, 208), (0, 208)]
    b = [(80, 96), (256, 96), (256, 208), (192, 208), (192, 144), (80, 144)]
    poly = lambda pts: "M" + "L".join(f"{px(x)} {px(y)}" for x, y in pts) + "Z"
    stem_w = max(1, round(16 * n / UNITS))
    left = px(128) - stem_w // 2
    side = max(1, round(24 * n / UNITS))
    top, taper, neck, foot = px(32), px(64), px(88), px(224)
    neck = max(neck, taper + 1)
    head = (f"M{left - side} {top}H{left + stem_w + side}V{taper}L{left + stem_w} {neck}V{foot}H{left}V{neck}"
            f"L{left - side} {taper}Z")
    r = px(56)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {n} {n}" width="{n}" height="{n}">{comment}\n'
            f'  <defs>\n'
            f'    <linearGradient id="rim" x1="0" y1="0" x2="1" y2="1">\n'
            f'      <stop offset="0" stop-color="#fff" stop-opacity="0.55"/>\n'
            f'      <stop offset="0.5" stop-color="#fff" stop-opacity="0.12"/>\n'
            f'      <stop offset="1" stop-color="#fff" stop-opacity="0.26"/>\n'
            f'    </linearGradient>\n'
            f'    <clipPath id="tile"><rect width="{n}" height="{n}" rx="{r}"/></clipPath>\n'
            f'  </defs>\n'
            f'  <rect width="{n}" height="{n}" rx="{r}" fill="{TILE}"/>\n'
            f'  <g clip-path="url(#tile)">\n'
            f'    <path d="{poly(a)}" fill="{CLIP_A}"/>\n'
            f'    <path d="{poly(b)}" fill="{CLIP_B}"/>\n'
            f'  </g>\n'
            f'  <path d="{head}" fill="{PLAYHEAD}"/>\n'
            f'  <rect width="{n}" height="{n}" rx="{r}" fill="none" stroke="url(#rim)" stroke-width="2"\n'
            f'        vector-effect="non-scaling-stroke" clip-path="url(#tile)"/>\n'
            f'</svg>\n')


MASTER_NOTE = ("\n  <!-- Premiere Agent Bridge icon. Generated by scripts/make_icon.py (edit the geometry there): an L-cut, "
               "the picture cutting before the sound,\n       under an orange playhead, on a deep purple tile with a "
               "one-pixel glass rim. -->")


def render(sizes=SIZES) -> dict:
    """{size: PIL.Image (RGBA)}: each size's own snapped SVG, drawn by the browser at that size, transparent."""
    from PIL import Image
    from playwright.sync_api import sync_playwright

    imgs = "".join(f'<img id="s{n}" width="{n}" height="{n}" src="data:image/svg+xml;base64,'
                   f'{base64.b64encode(icon_svg(n).encode()).decode()}">' for n in sizes)
    html = f"<!doctype html><style>html,body{{margin:0;background:transparent}}img{{display:block;margin:4px}}</style>{imgs}"
    out = {}
    with sync_playwright() as pw:
        browser = None
        for kw in ({"channel": "msedge"}, {"channel": "chrome"}, {}):
            try:
                browser = pw.chromium.launch(**kw)
                break
            except Exception:
                continue
        if browser is None:
            raise RuntimeError("no Chromium browser for Playwright (install Edge or Chrome, or `playwright install`)")
        page = browser.new_page(device_scale_factor=1)
        page.set_content(html)
        page.wait_for_timeout(200)
        for n in sizes:
            out[n] = Image.open(io.BytesIO(page.locator(f"#s{n}").screenshot(omit_background=True))).convert("RGBA")
        browser.close()
    return out


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--preview", default=None, help="also write every size side by side on a dark strip (PNG)")
    args = p.parse_args(argv)
    try:
        from PIL import Image
    except ImportError:
        print("Needs Pillow: pip install pillow", file=sys.stderr)
        return 1
    SVG.write_bytes(icon_svg(UNITS, MASTER_NOTE).encode("utf-8"))
    print(f"wrote {SVG}")
    frames = render()
    bad = [n for n, im in frames.items() if im.size != (n, n)]
    if bad:
        print(f"wrong frame sizes from the browser: {bad}", file=sys.stderr)
        return 1
    big = frames[max(SIZES)]
    big.save(ICO, format="ICO", sizes=[(n, n) for n in SIZES],
             append_images=[frames[n] for n in SIZES if n != max(SIZES)])
    print(f"wrote {ICO} ({', '.join(map(str, SIZES))} px)")
    frames[PANEL_SIZE].save(PANEL_PNG, format="PNG")
    print(f"wrote {PANEL_PNG} ({PANEL_SIZE} px)")
    if args.preview:
        w = sum(SIZES) + 16 * (len(SIZES) + 1)
        sheet = Image.new("RGBA", (w, max(SIZES) + 32), (32, 32, 32, 255))
        x = 16
        for n in SIZES:
            sheet.alpha_composite(frames[n], (x, 16 + max(SIZES) - n))
            x += n + 16
        sheet.save(args.preview)
        print(f"wrote {args.preview}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
