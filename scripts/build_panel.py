"""Bundle the panel into one self-contained main.js: the fallback if UXP's CommonJS `require` of
plugin/lib/*.js does not work in a Premiere build.

    python scripts/build_panel.py --out PATH [--plugin DIR] [--assets]

The bundle holds a tiny module registry with every plugin/lib/*.js file; main.js runs unchanged inside
it with a `require` that resolves "./lib/<name>.js" from the registry and passes "premierepro" / "uxp"
to the host's require. Lib modules get a require that only allows those two. The panel then reports
`modules: "bundle"` in ping. --assets also copies index.html and manifest.json next to the bundle, so
the output folder is a loadable plugin (without lib/). Not used unless the live spike fails.
"""

import argparse
import json
import re
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
PLUGIN = REPO / "plugin"
HEADER = "// Generated by scripts/build_panel.py from plugin/main.js and plugin/lib/*.js. Do not edit.\n"
LOCAL_REQUIRE = re.compile(r"""require\(\s*["'](\.[^"']*)["']\s*\)""")
LIB_NAME = re.compile(r"^\./lib/[A-Za-z0-9_]+\.js$")
HOST_MODULES = ("premierepro", "uxp")


def _read(path: Path) -> str:
    return path.read_bytes().decode("utf-8").replace("\r\n", "\n")


def build(plugin_dir: Path = PLUGIN) -> str:
    """The bundle's text. Raises ValueError when main.js requires a local file the bundle lacks."""
    plugin_dir = Path(plugin_dir)
    main = _read(plugin_dir / "main.js")
    libs = {f"./lib/{p.name}": _read(p) for p in sorted((plugin_dir / "lib").glob("*.js"))}
    wanted = LOCAL_REQUIRE.findall(main)
    bad = [w for w in wanted if not LIB_NAME.match(w) or w not in libs]
    if bad:
        raise ValueError(f"main.js requires files the bundle cannot provide: {', '.join(bad)}")
    for name, source in libs.items():
        local = LOCAL_REQUIRE.findall(source)
        if local:
            raise ValueError(f"{name} requires local files ({', '.join(local)}); lib modules get their deps from main.js")

    hosts = json.dumps(list(HOST_MODULES))
    out = [HEADER, "(function (hostRequire) {\n", "  var definitions = {};\n"]
    for name, source in libs.items():
        out.append(f"  definitions[{json.dumps(name)}] = function (module, exports, require) {{\n")
        out.append(source if source.endswith("\n") else source + "\n")
        out.append("  };\n")
    out.append(f"""  var hostModules = {hosts};
  var cache = {{}};
  function fromHost(name) {{
    if (hostModules.indexOf(name) >= 0) return hostRequire(name);
    return undefined;
  }}
  function libRequire(name) {{
    var m = fromHost(name);
    if (m !== undefined) return m;
    throw new Error("Agent Bridge bundle: lib modules must not require " + JSON.stringify(name));
  }}
  function bundleRequire(name) {{
    if (Object.prototype.hasOwnProperty.call(definitions, name)) {{
      if (!cache[name]) {{
        var module = {{ exports: {{}} }};
        cache[name] = module;
        definitions[name].call(module.exports, module, module.exports, libRequire);
      }}
      return cache[name].exports;
    }}
    var m = fromHost(name);
    if (m !== undefined) return m;
    throw new Error("Agent Bridge bundle: cannot require " + JSON.stringify(name));
  }}
  bundleRequire.bundle = true;
  (function (require) {{
""")
    out.append(main if main.endswith("\n") else main + "\n")
    out.append("  })(bundleRequire);\n")
    out.append('})(typeof require === "function" ? require : function (name) { throw new Error("require is unavailable: " + name); });\n')
    return "".join(out)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Bundle plugin/main.js and plugin/lib/*.js into one main.js.")
    parser.add_argument("--out", required=True, help="output file (e.g. a main.js in a scratch plugin folder)")
    parser.add_argument("--plugin", default=str(PLUGIN), help="plugin folder to bundle (default: plugin/)")
    parser.add_argument("--assets", action="store_true", help="also copy index.html and manifest.json next to --out")
    args = parser.parse_args(argv)
    plugin_dir = Path(args.plugin)
    if args.assets and Path(args.out).name != "main.js":
        print("build_panel: --assets needs --out .../main.js (index.html loads main.js)", file=sys.stderr)
        return 2
    try:
        text = build(plugin_dir)
    except (OSError, ValueError) as e:
        print(f"build_panel: {e}", file=sys.stderr)
        return 1
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(text.encode("utf-8"))
    if args.assets:
        for name in ("index.html", "manifest.json"):
            shutil.copyfile(plugin_dir / name, out.parent / name)
    print(f"build_panel: wrote {out} ({len(text.encode('utf-8'))} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
